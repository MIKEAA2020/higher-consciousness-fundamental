def data_table(story, caption, headers, rows, ratios, font_size=8.8,
               header_font=9.0, center_cols=()):
    """Standard data table: Paragraph cells, palette colors, centered.

    ratios must sum to ~1.0; widths scaled to 100% of available width.
    """
    assert abs(sum(ratios) - 1.0) < 0.01, 'ratios must sum to 1.0'
    col_widths = [r * AVAIL_W for r in ratios]
    assert sum(col_widths) <= AVAIL_W + 0.5

    th_style = ParagraphStyle('THx', parent=S['th'], fontSize=header_font,
                              leading=header_font + 3.5)
    td_style = ParagraphStyle('TDx', parent=S['td'], fontSize=font_size,
                              leading=font_size + 3.4)
    td_c_style = ParagraphStyle('TDCx', parent=td_style, alignment=TA_CENTER)

    data = [[Paragraph('<b>%s</b>' % h, th_style) for h in headers]]
    for row in rows:
        cells = []
        for ci, cell in enumerate(row):
            st = td_c_style if ci in center_cols else td_style
            cells.append(Paragraph(_nb_dash(cell), st))
        data.append(cells)

    tbl = Table(data, colWidths=col_widths, hAlign='CENTER', repeatRows=1)
    style_cmds = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0, 0), (-1, 0), TABLE_HEADER_TEXT),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        bg = TABLE_ROW_ODD if i % 2 == 1 else TABLE_ROW_EVEN
        style_cmds.append(('BACKGROUND', (0, i), (-1, i), bg))
    tbl.setStyle(TableStyle(style_cmds))

    story.append(Spacer(1, 16))
    if len(rows) <= 12:
        story.append(KeepTogether([tbl, Spacer(1, 6),
                                    Paragraph(caption, S['caption'])]))
    else:
        story.append(tbl)
        story.append(Spacer(1, 6))
        story.append(Paragraph(caption, S['caption']))
    story.append(Spacer(1, 16))


def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        w, h = el.wrap(AVAIL_W, PAGE_H)
        total_h += h
    if total_h <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)
