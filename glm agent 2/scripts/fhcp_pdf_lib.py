# ━━ Doc template with TOC + zone-aware footer ━━━━━━━━━━━━━━━━━━━━━━━━━━━
class BodyStartMarker(Flowable):
    """Zero-size marker: records the page where body content begins."""
    def __init__(self):
        Flowable.__init__(self)
        self.width = 0
        self.height = 0

    def wrap(self, aw, ah):
        return (0, 0)

    def draw(self):
        pass


class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if isinstance(flowable, BodyStartMarker):
            self._body_start = self.page
            return
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            # Report the DISPLAYED page number (arabic body numbering),
            # so TOC entries match the printed footers.
            body_start = getattr(self, '_body_start', None)
            if body_start is not None and self.page >= body_start:
                page = self.page - body_start + 1
            else:
                page = self.page
            self.notify('TOCEntry', (level, text, page, key))


_ROMAN = {1: 'i', 2: 'ii', 3: 'iii', 4: 'iv', 5: 'v', 6: 'vi', 7: 'vii',
          8: 'viii', 9: 'ix', 10: 'x', 11: 'xi', 12: 'xii'}


def paint_page(canvas, doc):
    """Header + footer painter: roman for front matter, arabic for body."""
    canvas.saveState()
    # Header: doc title left, accent rule under it
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 0.62 * inch, 'The Fundamental Higher Consciousness Premise')
    canvas.drawRightString(PAGE_W - MARGIN, PAGE_H - 0.62 * inch, 'Steelman Audit and Consolidation')
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 0.70 * inch, PAGE_W - MARGIN, PAGE_H - 0.70 * inch)
    # Footer: light rule + author left + bare page number right
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 0.62 * inch, PAGE_W - MARGIN, 0.62 * inch)
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 0.44 * inch, DOC_AUTHOR)
    body_start = getattr(doc, '_body_start', None)
    if body_start is None or doc.page < body_start:
        label = _ROMAN.get(doc.page, str(doc.page))
    else:
        label = str(doc.page - body_start + 1)
    canvas.drawRightString(PAGE_W - MARGIN, 0.44 * inch, label)
    canvas.restoreState()


