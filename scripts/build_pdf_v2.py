# ── Doc template with TOC support ────────────────────────────────────────
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))

def add_heading(text, style, level=0):
    key = 'h_' + hashlib.md5((str(level) + text).encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, md(text)), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        w, h = el.wrap(AVAIL_W, PAGE_H)
        total_h += h
    if total_h <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)

def quote_block(text):
    inner = Paragraph(md(text), QUOTE)
    t = Table([[inner]], colWidths=[AVAIL_W * 0.92], hAlign='CENTER')
    t.setStyle(TableStyle([
        ('LINEBEFORE', (0, 0), (0, -1), 2, ACCENT),
        ('BACKGROUND', (0, 0), (-1, -1), SECTION_BG),
        ('LEFTPADDING', (0, 0), (-1, -1), 14),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 8),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
    ]))
    return [Spacer(1, 6)] + safe_keep_together([t]) + [Spacer(1, 10)]

def data_table(spec):
    ratios = spec['ratios']
    assert abs(sum(ratios) - 1.0) < 1e-6, 'ratios must sum to 1.0'
    col_widths = [r * AVAIL_W for r in ratios]
    assert sum(col_widths) <= AVAIL_W + 0.5
    header = [Paragraph('<b>%s</b>' % md(h), TH) for h in spec['header']]
    rows = [header]
    for r in spec['rows']:
        rows.append([Paragraph(md(cell), TC) for cell in r])
    t = Table(rows, colWidths=col_widths, hAlign='CENTER', repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [TABLE_ROW_EVEN, TABLE_ROW_ODD]),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, 0), 'MIDDLE'),
        ('VALIGN', (0, 1), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]))
    cap = Paragraph(md(spec['caption']), CAPTION)
    out = [Spacer(1, 12)]
    if len(spec['rows']) <= 5:
        out += safe_keep_together([t, cap])
    else:
        out += [t, cap]
    out += [Spacer(1, 10)]
    return out

# ── Header / footer ──────────────────────────────────────────────────────
def on_page(canvas, doc):
    canvas.saveState()
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 0.60 * inch, C.DOC_TITLE.upper())
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 0.70 * inch, PAGE_W - MARGIN, PAGE_H - 0.70 * inch)
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.4)
    canvas.line(MARGIN, 0.62 * inch, PAGE_W - MARGIN, 0.62 * inch)
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 0.46 * inch, C.DOC_AUTHOR)
    num = 'i' if doc.page == 1 else str(doc.page - 1)
    canvas.drawRightString(PAGE_W - MARGIN, 0.46 * inch, num)
    canvas.restoreState()

# ── Build story ──────────────────────────────────────────────────────────
story = []

toc = TableOfContents()
toc.levelStyles = [TOC_L0, TOC_L1]
story.append(Paragraph('<b>Table of Contents</b>', TOC_TITLE))
story.append(toc)
story.append(PageBreak())

story.append(Paragraph(md(C.META_NOTE), NOTE))

for sec in C.SECTIONS:
    story.append(CondPageBreak(AVAIL_H * 0.25))
    h1 = add_heading('%s. %s' % (sec['num'], sec['title']), H1, level=0)
    rule = HRFlowable(width='100%', thickness=1.2, color=ACCENT,
                      spaceBefore=0, spaceAfter=12)
    blocks = sec['blocks']
    first = blocks[0]
    if first[0] == 'body':
        story.extend(safe_keep_together([h1, rule, Paragraph(md(first[1]), BODY)]))
        rest = blocks[1:]
    else:
        story.extend(safe_keep_together([h1, rule]))
        rest = blocks
    for kind, payload in ((b[0], b[1]) for b in rest):
        if kind == 'body':
            story.append(Paragraph(md(payload), BODY))
        elif kind == 'h2':
            story.extend(safe_keep_together([add_heading(payload, H2, level=1)]))
        elif kind == 'quote':
            story.extend(quote_block(payload))
        elif kind == 'table':
            story.extend(data_table(payload))
        elif kind == 'note':
            story.append(Paragraph(md(payload), NOTE))

doc = TocDocTemplate(
    OUT_BODY, pagesize=A4,
    leftMargin=MARGIN, rightMargin=MARGIN,
    topMargin=1.05 * inch, bottomMargin=0.95 * inch,
    title=C.DOC_TITLE + ' — ' + 'Trilogy Edition: Critique, Steelman, Survival Test',
    author='Z.ai', creator='Z.ai',
    subject=C.DOC_SUBTITLE,
)
doc.multiBuild(story, onFirstPage=on_page, onLaterPages=on_page)
print('body pdf written:', OUT_BODY)
