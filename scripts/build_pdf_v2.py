# ── Markup: **bold**, *italic* → ReportLab tags ─────────────────────────
def esc(t):
    # NOTE: entities are built by concatenation so code.sanitize's
    # html.unescape pass cannot decode them back into raw characters.
    AMP = '&' + 'amp;'
    LT  = '&' + 'lt;'
    GT  = '&' + 'gt;'
    return t.replace('&', AMP).replace('<', LT).replace('>', GT)

def md(t):
    t = esc(t)
    t = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', t, flags=re.S)
    t = re.sub(r'\*(.+?)\*', r'<i>\1</i>', t, flags=re.S)
    # Bind em-dashes to the preceding word (prevents line-start dash)
    t = t.replace(' \u2014 ', '\u00a0\u2014 ')
    return t

